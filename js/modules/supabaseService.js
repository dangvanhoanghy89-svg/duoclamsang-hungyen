export function getSupabaseClient() {
  if (supabaseClient) return supabaseClient;
  const { url, key } = getSupabaseCredentials();
  if (url && key && window.supabase) {
    try {
      supabaseClient = window.supabase.createClient(url, key);
    } catch (e) {
      console.warn("Lỗi khởi tạo Supabase Client:", e);
    }
  }
  return supabaseClient;
}

export async function testSupabaseConnection(customUrl = null, customKey = null) {
  const url = customUrl || getSupabaseCredentials().url;
  const key = customKey || getSupabaseCredentials().key;

  if (!url || !key) {
    return { ok: false, message: "Chưa cấu hình Supabase URL hoặc Key." };
  }
  if (!window.supabase) {
    return { ok: false, message: "Thư viện Supabase JS chưa được tải." };
  }

  try {
    const testClient = window.supabase.createClient(url, key);
    const { data, error } = await testClient.from("custom_drugs").select("id").limit(1);
    if (error) {
      if (error.code === "42P01") {
        return {
          ok: false,
          needSql: true,
          message: "Kết nối thành công tới Supabase, nhưng bảng 'custom_drugs' chưa tồn tại. Vui lòng chạy mã SQL khởi tạo."
        };
      }
      if (error.code === "42501") {
        return {
          ok: false,
          needSql: true,
          message: "Quyền truy cập bảng bị hạn chế (RLS). Vui lòng chạy mã SQL khởi tạo để mở quyền."
        };
      }
      return { ok: false, message: `Lỗi từ Supabase: ${error.message}` };
    }
    return {
      ok: true,
      message: "Kết nối thành công! Đã kết nối thông suốt với Cơ sở dữ liệu Supabase Cloud."
    };
  } catch (err) {
    return { ok: false, message: `Lỗi kết nối mạng: ${err.message}` };
  }
}

export async function syncCustomDrugsFromCloud() {
  const client = getSupabaseClient();
  if (!client) return false;

  try {
    const { data, error } = await client.from("custom_drugs").select("*");
    if (error) {
      console.warn("Lỗi tải custom_drugs từ Supabase:", error);
      return false;
    }

    if (Array.isArray(data) && data.length > 0) {
      const raw = localStorage.getItem(CUSTOM_DRUGS_STORAGE_KEY);
      const store = raw ? JSON.parse(raw) : { deletedIds: [], modified: {}, addedDrugs: [] };
      if (!store.addedDrugs) store.addedDrugs = [];

      data.forEach(row => {
        const drug = row.data || row;
        if (!drug || !drug.id) return;
        const idx = store.addedDrugs.findIndex(d => d.id === drug.id);
        if (idx >= 0) {
          store.addedDrugs[idx] = drug;
        } else {
          store.addedDrugs.push(drug);
        }
      });

      localStorage.setItem(CUSTOM_DRUGS_STORAGE_KEY, JSON.stringify(store));
      console.log(`Đã đồng bộ ${data.length} thuốc từ Supabase Cloud!`);
      if (window.renderDrugList) window.renderDrugList();
      return true;
    }
  } catch (e) {
    console.warn("Lỗi syncCustomDrugsFromCloud:", e);
  }
  return false;
}

export async function saveDrugToCloud(drugData) {
  const client = getSupabaseClient();
  if (!client || !drugData || !drugData.id) return false;

  try {
    const { error } = await client.from("custom_drugs").upsert({
      id: drugData.id,
      data: drugData,
      updated_at: new Date().toISOString()
    });
    if (error) {
      console.warn("Lỗi lưu thuốc lên Supabase Cloud:", error);
      return false;
    }
    console.log("Đã lưu thuốc lên Supabase Cloud:", drugData.name);
    return true;
  } catch (e) {
    console.warn("Lỗi saveDrugToCloud:", e);
    return false;
  }
}

export async function deleteDrugFromCloud(drugId) {
  const client = getSupabaseClient();
  if (!client || !drugId) return false;

  try {
    const { error } = await client.from("custom_drugs").delete().eq("id", drugId);
    if (error) {
      console.warn("Lỗi xóa thuốc trên Supabase Cloud:", error);
      return false;
    }
    console.log("Đã xóa thuốc trên Supabase Cloud:", drugId);
    return true;
  } catch (e) {
    console.warn("Lỗi deleteDrugFromCloud:", e);
    return false;
  }
}

export function copySupabaseSchemaSql() {
  if (navigator.clipboard) {
    navigator.clipboard.writeText(SUPABASE_SCHEMA_SQL).then(() => {
      alert("Đã sao chép toàn bộ mã SQL khởi tạo CSDL vào bộ nhớ tạm!\n\nBây giờ bạn hãy mở Supabase Dashboard -> SQL Editor -> Dán (Ctrl+V) và bấm RUN.");
    }).catch(() => {
      prompt("Hãy sao chép đoạn mã SQL dưới đây:", SUPABASE_SCHEMA_SQL);
    });
  } else {
    prompt("Hãy sao chép đoạn mã SQL dưới đây:", SUPABASE_SCHEMA_SQL);
  }
}

